// Static-site build step: points the Mini App at the API service.
// API_URL=https://dragondrop-api.onrender.com node scripts/build-web-config.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const api = String(process.env.API_URL || '').replace(/\/+$/, '');
if (api && !/^https:\/\//.test(api)) throw new Error('API_URL must start with https://');
const file = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web', 'config.js');
writeFileSync(file, `// Generated by scripts/build-web-config.mjs\nwindow.BS_CONFIG = { api: ${JSON.stringify(api)} };\n`);
console.log('web/config.js ->', api || '(same origin)');
